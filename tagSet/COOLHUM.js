function COOLHUM(ST1, ST2, ST3, ST4, COOLHUM_BASE) {
    const stMap = { "ST1": ST1, "ST2": ST2, "ST3": ST3, "ST4": ST4 }
    return COOLHUM_BASE.map(item => {
        let address = item.address
        for (const [key, val] of Object.entries(stMap)) {
            address = address.replace(new RegExp(key, "g"), val)
        }
        return { ...item, address }
    })
}

